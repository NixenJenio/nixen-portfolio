type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (value: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

function getStoredLocale(): Locale {
  const stored = window.localStorage.getItem("nixen-locale");
  return stored === "id" || stored === "zh" ? stored : "en";
}

function getServerLocale(): Locale {
  return "en";
}

function subscribeToLocale(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener("nixen-locale-change", onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener("nixen-locale-change", onChange);
  };
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const locale = useSyncExternalStore(subscribeToLocale, getStoredLocale, getServerLocale);

  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : locale;
    const title = locale === "id"
      ? "NIXEN — Software Engineer / Antusias Data & AI"
      : locale === "zh"
        ? "NIXEN — 软件工程师 / 数据与 AI 爱好者"
        : "NIXEN — Software Engineer / Data & AI Enthusiast";
    document.title = title;
    const titleObserver = new MutationObserver(() => {
      if (document.title !== title) document.title = title;
    });
    titleObserver.observe(document.head, { childList: true, subtree: true, characterData: true });
    return () => titleObserver.disconnect();
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    window.localStorage.setItem("nixen-locale", next);
    window.dispatchEvent(new Event("nixen-locale-change"));
  }, []);
  const t = useCallback((value: string) => {
    if (locale === "id") return indonesian[value] ?? value;
    if (locale === "zh") return simplifiedChinese[value] ?? value;
    return value;
  }, [locale]);

  return <LocaleContext.Provider value={{ locale, setLocale, t }}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used inside LocaleProvider");
  return value;
}
